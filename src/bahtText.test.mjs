// Run: node src/bahtText.test.mjs
import assert from 'node:assert'
import { bahtText } from './bahtText.js'

const eq = (n, want) => assert.strictEqual(bahtText(n), want, `${n} → ได้ "${bahtText(n)}" ควรเป็น "${want}"`)

// --- หลักเดียวและศูนย์ ---
eq(0, 'ศูนย์บาทถ้วน')
eq(1, 'หนึ่งบาทถ้วน')
eq(9, 'เก้าบาทถ้วน')

// --- กฎพิเศษของภาษาไทย: สิบ / ยี่สิบ / เอ็ด ---
eq(10, 'สิบบาทถ้วน')          // ไม่ใช่ "หนึ่งสิบ"
eq(11, 'สิบเอ็ดบาทถ้วน')      // ไม่ใช่ "สิบหนึ่ง"
eq(20, 'ยี่สิบบาทถ้วน')       // ไม่ใช่ "สองสิบ"
eq(21, 'ยี่สิบเอ็ดบาทถ้วน')
eq(35, 'สามสิบห้าบาทถ้วน')
eq(101, 'หนึ่งร้อยเอ็ดบาทถ้วน')
eq(111, 'หนึ่งร้อยสิบเอ็ดบาทถ้วน')

// --- หลักร้อย/พัน/หมื่น/แสน ---
eq(200, 'สองร้อยบาทถ้วน')
eq(420, 'สี่ร้อยยี่สิบบาทถ้วน')          // ตรงกับตัวอย่างใน mockup
eq(1410, 'หนึ่งพันสี่ร้อยสิบบาทถ้วน')
eq(2141, 'สองพันหนึ่งร้อยสี่สิบเอ็ดบาทถ้วน')
eq(8400, 'แปดพันสี่ร้อยบาทถ้วน')
eq(71344, 'เจ็ดหมื่นหนึ่งพันสามร้อยสี่สิบสี่บาทถ้วน')
eq(100000, 'หนึ่งแสนบาทถ้วน')

// --- หลักล้าน ---
eq(1000000, 'หนึ่งล้านบาทถ้วน')
eq(1200000, 'หนึ่งล้านสองแสนบาทถ้วน')
eq(1000001, 'หนึ่งล้านเอ็ดบาทถ้วน')      // เอ็ด หลังล้าน

// --- สตางค์ ---
eq(0.5, 'ศูนย์บาทห้าสิบสตางค์')
eq(1.25, 'หนึ่งบาทยี่สิบห้าสตางค์')
eq(200.75, 'สองร้อยบาทเจ็ดสิบห้าสตางค์')
eq(1410.01, 'หนึ่งพันสี่ร้อยสิบบาทหนึ่งสตางค์')  // 1 เดี่ยว ๆ อ่าน "หนึ่ง" ไม่ใช่ "เอ็ด"
eq(1410.21, 'หนึ่งพันสี่ร้อยสิบบาทยี่สิบเอ็ดสตางค์')  // แต่ 21 ใช้ "เอ็ด"

// --- ปัดเศษที่สตางค์ ห้ามให้บาทเพี้ยน ---
eq(9.999, 'สิบบาทถ้วน')       // ปัดขึ้นเป็น 10.00 พอดี
eq(0.004, 'ศูนย์บาทถ้วน')     // ปัดลงหายไป

// --- ติดลบ (คืนเงิน) ---
eq(-200, 'ลบสองร้อยบาทถ้วน')

// --- ค่าที่ใช้ไม่ได้ ---
assert.strictEqual(bahtText('abc'), '')
assert.strictEqual(bahtText(Infinity), '')

console.log('bahtText: ผ่านหมด ✓')
